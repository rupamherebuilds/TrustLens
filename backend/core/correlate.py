from core.models import Finding


def correlate(findings: list[Finding]) -> list[Finding]:
    correlated_findings = []

    # Collect finding IDs so we can quickly check which security issues were detected.
    finding_ids = {finding.id for finding in findings}

    # Rule 1: Check if a known brand is being impersonated through an IP-based URL.
    # Both findings together indicate a stronger suspicious pattern.
    if "BRAND_IMPERSONATION" in finding_ids and "IP_BASED_URL" in finding_ids:
        correlated_findings.append(
            Finding(
                id="BRAND_AND_IP_URL",
                source="correlation",
                description="The URL impersonates a known brand and uses an IP address.",
                points=30,
                data={
                    # Keep the IDs of the findings that triggered this correlation.
                    "related_findings": [
                        "BRAND_IMPERSONATION",
                        "IP_BASED_URL"
                    ]
                }
            )
        )

    # Rule 2: Check whether the URL module detected three or more suspicious signals.
    # Multiple suspicious characteristics together may indicate a phishing attempt.
    url_findings = [
        finding for finding in findings
        if finding.source == "url"
    ]

    if len(url_findings) >= 3:
        correlated_findings.append(
            Finding(
                id="MULTIPLE_URL_SIGNALS",
                source="correlation",
                description="The URL contains multiple suspicious characteristics.",
                points=20,
                data={
                    # Store all URL findings that contributed to this correlation.
                    "related_findings": [
                        finding.id for finding in url_findings
                    ]
                }
            )
        )

    # Return all correlation findings generated by the rules above.
    return correlated_findings