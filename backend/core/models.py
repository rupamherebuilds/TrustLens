from typing import Any, Literal

from pydantic import BaseModel, Field


class ScanContext(BaseModel):
    # Stores the basic information about a URL scan.
    scan_id: str
    url: str
    host: str
    registered_domain: str | None = None

    # Stores additional information collected during the scan.
    # Each module can add its results here for other modules to use.
    facts: dict[str, Any] = Field(default_factory=dict)


class Finding(BaseModel):
    # Represents a single security issue detected by a module.
    id: str
    source: str
    description: str

    # Risk points assigned to this finding (0 to 100).
    points: int = Field(ge=0, le=100)

    # Stores extra details related to the detected issue.
    data: dict[str, Any] = Field(default_factory=dict)


class ModuleResult(BaseModel):
    # Represents the output returned by an analysis module.
    module: str

    # Indicates whether the module completed successfully or failed.
    status: Literal["success", "failed"] = "success"

    # Contains all findings generated by the module.
    findings: list[Finding] = Field(default_factory=list)

    # Stores the error message if the module fails.
    error: str | None = None